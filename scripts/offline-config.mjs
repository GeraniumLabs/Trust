// Writes .wrangler.offline.jsonc: wrangler.jsonc without the Workers AI binding, so local dev
// and tests run with no Cloudflare login. The judge then falls back to the heuristic, or to a
// System One URL if TRUST_JUDGE_URL is set (for a local Kev or the eval oracle).
import { readFileSync, writeFileSync } from "node:fs";
const src = readFileSync(new URL("../wrangler.jsonc", import.meta.url), "utf8");
const out = src.replace(/^\s*"ai":\s*\{[^}]*\},?\s*$/m, "");
if (out === src) throw new Error("no ai binding found in wrangler.jsonc");
writeFileSync(new URL("../.wrangler.offline.jsonc", import.meta.url), `// Generated by scripts/offline-config.mjs. Do not edit.\n${out}`);
